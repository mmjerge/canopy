"""GPU-calibrated eviction-policy comparison: adaptive vs LRU/LFU/offline in realized time.

vLLM ships LRU block eviction; our claim is that the recency-weighted-frequency
(adaptive) policy matches LFU when stationary and dominates everything after a
popularity shift. Rather than forking the engine, this is a trace-driven comparison in
*realized GPU time*: replay the real-prompt workload through each policy (the exact
simulator of ``canopy.bandits.prefix_cache``) and convert tokens-reused into
milliseconds of prefill saved using a calibration measured on the live server
(``vllm_prefix_cache_eval.py --calibrate``).

This is Tier-1.5 evidence: real prompts, real per-token GPU cost, our eviction
decisions -- not a full in-engine deployment (Tier 2, scoped in the paper's
limitations).

Run (offline; pass the calibration you measured, default 1.06 ms/token from an A10G):
    uv run --extra bench --extra plot python examples/systems/vllm_policy_eval.py \\
        --ms-per-token 1.06
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "llm_routing"))

from canopy.bandits import offline_optimal, run_cache  # noqa: E402

HORIZON = 20_000
BUDGET = 128
N_SEEDS = 6
POLICIES = ["lru", "lfu", "adaptive", "offline"]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--ms-per-token",
        type=float,
        default=1.06,
        help="prefill ms one cached token saves (measure with vllm_prefix_cache_eval.py --calibrate)",
    )
    ap.add_argument("--corpus", default="alpaca", choices=["alpaca", "dolly"])
    args = ap.parse_args()

    from prefix_cache import load_real_prompts, make_stream  # real-prompt workload

    try:
        prompts = load_real_prompts(args.corpus)
    except Exception as e:  # noqa: BLE001
        print(f"Could not load the corpus ({type(e).__name__}: {e}); uv sync --extra bench")
        return
    print(
        f"trace-driven eviction comparison: {args.corpus}, budget {BUDGET}, "
        f"calibration {args.ms_per_token} ms/token"
    )

    stationary = {p: [] for p in POLICIES}
    transient = {p: [] for p in POLICIES}
    for seed in range(N_SEEDS):
        stream_s = make_stream(prompts, HORIZON, np.random.default_rng(seed))
        stream_x = make_stream(
            prompts, HORIZON, np.random.default_rng(100 + seed), shift_at=HORIZON // 2
        )
        window = slice(HORIZON // 2, HORIZON // 2 + 2500)
        for p in POLICIES:
            run = offline_optimal if p == "offline" else lambda s, b, _p=p: run_cache(s, b, policy=_p)
            stationary[p].append(run(stream_s, BUDGET).avg_savings)
            transient[p].append(float(run(stream_x, BUDGET).savings_curve[window].mean()))

    ms = args.ms_per_token
    pretty = {
        "lru": "LRU (engine default)",
        "lfu": "LFU",
        "adaptive": "\\textbf{Adaptive (ours)}",
        "offline": "Offline-optimal",
    }
    print(f"{'policy':>22s} {'stationary (ms saved)':>22s} {'post-shift (ms saved)':>22s}")
    rows = []
    stat_ms, shift_ms = {}, {}
    for p in POLICIES:
        stat_ms[p] = float(np.mean(stationary[p])) * ms
        shift_ms[p] = float(np.mean(transient[p])) * ms
        print(f"{p:>22s} {stat_ms[p]:22.1f} {shift_ms[p]:22.1f}")
        rows.append(f"{pretty[p]} & {stat_ms[p]:.1f} & {shift_ms[p]:.1f} \\\\")

    import matplotlib.pyplot as plt  # noqa: E402

    from _plotstyle import FIGURE_DIR, PALETTE, save_figure, set_style  # noqa: E402

    set_style()
    fig, ax = plt.subplots(figsize=(7, 4.4))
    x = np.arange(len(POLICIES))
    w = 0.38
    ax.bar(x - w / 2, [stat_ms[p] for p in POLICIES], w, color=PALETTE["gray"], label="stationary")
    ax.bar(x + w / 2, [shift_ms[p] for p in POLICIES], w, color=PALETTE["orange"], label="post-shift")
    ax.set_xticks(x, POLICIES)
    ax.set_ylabel("realized TTFT saved (ms)")
    ax.set_title(
        f"GPU-calibrated eviction: adaptive vs LRU/LFU ({args.corpus}, {ms:.2f} ms/token)"
    )
    ax.legend()
    fig.tight_layout()
    out = save_figure(fig, "vllm_policy_eval")
    print(f"\nsaved chart to {out} (+ .png)")

    tex = (
        "% GPU-calibrated eviction comparison (auto-generated by vllm_policy_eval.py)\n"
        "\\begin{tabular}{lrr}\n\\toprule\n"
        "Policy & TTFT saved, stationary (ms) & TTFT saved, post-shift (ms) \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )
    FIGURE_DIR.mkdir(parents=True, exist_ok=True)
    (FIGURE_DIR / "vllm_policy_eval_table.tex").write_text(tex)
    print(f"wrote LaTeX table to {FIGURE_DIR / 'vllm_policy_eval_table.tex'}")


if __name__ == "__main__":
    main()
